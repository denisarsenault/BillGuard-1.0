#!/bin/bash
#
# Assembles the BillGuard Chrome extension.
#
# The popup (popup.html, popup.css, popup.js) and the icons are the Safari Web
# Extension's, from ../BillGuardWebExtension/Resources. This folder adds the
# Chrome manifest and backend. The result is build/BillGuard-Chrome, which can
# be loaded in Chrome (chrome://extensions, Developer mode, Load unpacked), and
# build/BillGuard-Chrome.zip for the Chrome Web Store.
#
set -euo pipefail
cd "$(dirname "$0")"

shared=../BillGuardWebExtension/Resources
out=build/BillGuard-Chrome

rm -rf build
mkdir -p "$out"
cp "$shared"/popup.html "$shared"/popup.css "$shared"/popup.js "$shared"/*.png "$out"/
cp manifest.json "$out"/

# backend.js: the codes BillGuard knows (a positive signal for the analyzer,
# as in KnownProcedureCodes.swift), then the analyzer, then the backend.
{
    /usr/bin/python3 - ../BillGuard/Resources/medical_codes.json <<'PY'
import json, re, sys
codes = sorted({entry["code"] for entry in json.load(open(sys.argv[1]))
                if re.fullmatch(r"[0-9]{5}|[ABCDEGHJKLMPQRSTUV][0-9]{4}", entry["code"])})
print("// Generated by build.sh from BillGuard/Resources/medical_codes.json.")
print("const BILLGUARD_KNOWN_CODES = " + json.dumps(codes) + ";")
PY
    echo
    cat analyzer.js
    echo
    cat chrome-backend.js
} > "$out"/backend.js

(cd build && zip -qr BillGuard-Chrome.zip BillGuard-Chrome)
echo "Built $(pwd)/$out"
